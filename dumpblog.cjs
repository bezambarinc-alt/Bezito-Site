const { Client } = require('pg')
;(async () => {
  const c = new Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } })
  await c.connect()
  const cols = await c.query(`SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns WHERE table_name='blog_posts' ORDER BY ordinal_position`)
  console.log('=== SCHEMA ===')
  cols.rows.forEach(r => console.log(`${r.column_name} | ${r.data_type} | null=${r.is_nullable} | def=${r.column_default}`))
  const cnt = await c.query(`SELECT status, count(*) FROM blog_posts GROUP BY status`)
  console.log('=== STATUS ===', JSON.stringify(cnt.rows))
  const cat = await c.query(`SELECT category, count(*) FROM blog_posts WHERE status='live' GROUP BY category ORDER BY 2 DESC`)
  console.log('=== CATEGORIES ===', JSON.stringify(cat.rows))
  const recent = await c.query(`SELECT slug, title, date, category, author, schema_faq, schema_type, hero_image, display_order, length(body) AS bodylen FROM blog_posts WHERE status='live' ORDER BY date DESC LIMIT 12`)
  console.log('=== RECENT ===')
  recent.rows.forEach(r => console.log(JSON.stringify(r)))
  await c.end()
})().catch(e => { console.error(e.message); process.exit(1) })
